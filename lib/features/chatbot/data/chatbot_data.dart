class ChatMessage {
  final String text;
  final bool isUser;
  final DateTime time;
  final List<String>? quickReplies;

  ChatMessage({
    required this.text,
    required this.isUser,
    required this.time,
    this.quickReplies,
  });
}

class ChatbotEngine {
  static const List<String> greetings = [
    'مرحبا', 'هاي', 'السلام', 'أهلا', 'hello', 'hi', 'hey', 'مرحباً', 'أهلاً'
  ];

  static const List<String> farewells = [
    'مع السلامة', 'باي', 'وداعاً', 'goodbye', 'bye', 'شكرا', 'شكراً', 'thanks'
  ];

  static String getResponse(String input) {
    final lower = input.toLowerCase().trim();

    // Greetings
    if (greetings.any((g) => lower.contains(g))) {
      return 'أهلاً وسهلاً! 👋\nأنا مساعد تطبيق سلامتي. كيف أقدر أساعدك النهارده؟';
    }

    // Farewells
    if (farewells.any((f) => lower.contains(f))) {
      return 'مع السلامة! 😊\nنتمنى لك صحة وسلامة دايماً. لو احتجت أي مساعدة، إحنا هنا!';
    }

    // Medicine / Drug related
    if (_contains(lower, ['دواء', 'دوا', 'أدوية', 'أدوايه', 'medicine', 'drug', 'دوائي', 'tablet', 'حبة', 'كبسولة'])) {
      if (_contains(lower, ['بديل', 'alternative', 'بديله'])) {
        return '💊 بدائل الأدوية\n\nلو عايز تعرف بديل لدواء معين:\n1. افتح التطبيق\n2. ابحث عن الدواء في Drug Store\n3. اضغط على "بدائل الدواء"\n\nالتطبيق هيعرض لك كل البدائل المتاحة مع السعر والشركة المصنعة.';
      }
      if (_contains(lower, ['سعر', 'بكام', 'بكم', 'price', 'تمن'])) {
        return '💰 أسعار الأدوية\n\nلمعرفة سعر أي دواء:\n• افتح قسم "Drug Store" من الصفحة الرئيسية\n• ابحث باسم الدواء أو المادة الفعالة\n• هتلاقي السعر الرسمي والمتاح منه\n\nالأسعار بتتحدث بانتظام حسب السوق.';
      }
      if (_contains(lower, ['تفاصيل', 'معلومات', 'عن الدواء', 'تأثير', 'جرعة', 'أعراض'])) {
        return '📋 معلومات الدواء\n\nفي صفحة تفاصيل الدواء هتلاقي:\n✓ وصف الدواء والمادة الفعالة\n✓ الجرعات الموصى بها\n✓ الأعراض الجانبية المحتملة\n✓ السعر والتوافر\n✓ الشركة المصنعة\n\nابحث عنه في قسم Drug Store!';
      }
      return '💊 الأدوية في سلامتي\n\nالتطبيق بيوفر:\n• بحث شامل عن الأدوية\n• بدائل الأدوية\n• تفاصيل وجرعات\n• مسح الروشتة بالكاميرا\n\nعايز تعرف أكتر عن إيه بالظبط؟';
    }

    // Scan / OCR
    if (_contains(lower, ['scan', 'مسح', 'روشتة', 'كاميرا', 'صورة', 'صوره', 'وصفة طبية'])) {
      return '📸 مسح الروشتة\n\nخطوات مسح الروشتة الطبية:\n1. اضغط على أيقونة الكاميرا في الشاشة الرئيسية\n2. اختار "مسح الروشتة" أو "رفع صورة"\n3. صوّر الروشتة بوضوح\n4. التطبيق هيتعرف على الأدوية تلقائياً\n5. هيعرض لك الأدوية المتاحة وغير المتاحة\n\n⚠️ تأكد إن الإضاءة كويسة والصورة واضحة.';
    }

    // Pharmacy / Nearby
    if (_contains(lower, ['صيدلية', 'صيدليه', 'pharmacy', 'صيدليات', 'قريب', 'قريبة', 'nearby'])) {
      return '🏥 الصيدليات القريبة\n\nللعثور على أقرب صيدلية:\n1. افتح قسم "الصيدليات القريبة"\n2. فعّل خدمة الموقع الجغرافي\n3. التطبيق هيحدد موقعك ويعرض الصيدليات الأقرب\n4. تقدر تشوف:\n   • اسم الصيدلية وعنوانها\n   • المسافة منك\n   • ساعات العمل\n\n📍 تأكد إن إذن الموقع مفعّل في إعدادات الجوال.';
    }

    // Insurance
    if (_contains(lower, ['تأمين', 'تامين', 'insurance', 'وثيقة', 'تغطية', 'coverage'])) {
      if (_contains(lower, ['مزود', 'شركة', 'provider'])) {
        return '🏢 مزودي التأمين\n\nلاختيار شركة التأمين:\n1. افتح قسم "التأمين"\n2. اختار "اختيار مزود التأمين"\n3. هتلاقي قائمة بكل شركات التأمين المتاحة\n4. اختار الشركة المناسبة\n\nتقدر تقارن بين الشركات المختلفة والتغطيات المتاحة.';
      }
      if (_contains(lower, ['بيانات', 'معلومات', 'بطاقة'])) {
        return '📋 بيانات التأمين\n\nلإضافة بيانات التأمين:\n1. افتح ملف التأمين\n2. اضغط "إضافة معلومات التأمين"\n3. أدخل:\n   • رقم وثيقة التأمين\n   • اسم الشركة\n   • تاريخ انتهاء الوثيقة\n4. ارفع صورة البطاقة لو متاحة\n\nالمعلومات دي بتساعدك تستخدم التغطية التأمينية عند زيارة المرافق الطبية.';
      }
      return '🛡️ التأمين في سلامتي\n\nالتطبيق بيساعدك في:\n• عرض بروفايل التأمين الخاص بك\n• اختيار مزود التأمين\n• إضافة معلومات الوثيقة\n• معرفة الخدمات المغطاة\n• إيجاد مرافق تقبل تأمينك\n\nتريد معرفة أكتر عن أي جزء؟';
    }

    // Facilities / Hospitals
    if (_contains(lower, ['مستشفى', 'مستشفيات', 'مرفق', 'مرافق', 'hospital', 'facilities', 'عيادة', 'clinic'])) {
      return '🏨 المرافق الطبية\n\nللبحث عن مستشفى أو عيادة:\n1. افتح قسم "المرافق" من القائمة\n2. ابحث باسم المرفق أو الموقع\n3. فلتر حسب النوع:\n   • مستشفيات\n   • عيادات\n   • مراكز طبية\n4. اضغط على أي مرفق لتفاصيله\n\nتقدر تحفظ المفضلة منها في قائمة المفضلة.';
    }

    // Specialties / Doctors
    if (_contains(lower, ['تخصص', 'تخصصات', 'طبيب', 'دكتور', 'doctor', 'specialty', 'specialties'])) {
      return '👨‍⚕️ التخصصات الطبية\n\nللبحث عن تخصص طبي:\n1. افتح قسم "التخصصات"\n2. ابحث بالاسم أو تصفح القائمة\n3. اختار التخصص المناسب\n4. هتلاقي:\n   • وصف التخصص\n   • الأطباء المتاحين\n   • المرافق المتخصصة\n\nالتطبيق بيغطي طيف واسع من التخصصات الطبية.';
    }

    // Favorites
    if (_contains(lower, ['مفضلة', 'محفوظ', 'favorite', 'saved', 'احفظ'])) {
      return '❤️ المفضلة\n\nلإضافة أي عنصر للمفضلة:\n• اضغط على أيقونة القلب ❤️ بجانب أي دواء أو مرفق أو طبيب\n\nلعرض مفضلتك:\n• افتح قسم "المفضلة" من القائمة الجانبية\n• هتلاقي كل العناصر المحفوظة منظمة\n\nالمفضلة بتسهل عليك الوصول للعناصر اللي بتحتاجها باستمرار.';
    }

    // Profile / Account
    if (_contains(lower, ['حساب', 'بروفايل', 'بيانات', 'profile', 'account', 'تعديل', 'تحديث'])) {
      if (_contains(lower, ['تعديل', 'تحديث', 'تغيير', 'edit'])) {
        return '✏️ تعديل البروفايل\n\nلتعديل بيانات حسابك:\n1. افتح قسم "البروفايل"\n2. اضغط "تعديل البيانات"\n3. تقدر تعدل:\n   • الاسم والصورة الشخصية\n   • تاريخ الميلاد\n   • الجنس\n   • معلومات التواصل\n4. اضغط "حفظ" لتأكيد التغييرات.';
      }
      return '👤 البروفايل\n\nمن قسم البروفايل تقدر:\n• تشوف وتعدل بياناتك الشخصية\n• تدير معلومات التأمين\n• تشوف سجل البحث\n• التواصل مع الدعم الفني\n• تغيير إعدادات التطبيق\n\nهل تريد مساعدة في شيء معين؟';
    }

    // Sign in / Sign up / Password
    if (_contains(lower, ['تسجيل', 'دخول', 'login', 'signin', 'sign in', 'حساب جديد', 'signup'])) {
      return '🔐 تسجيل الدخول\n\nلتسجيل الدخول:\n1. افتح التطبيق\n2. أدخل البريد الإلكتروني وكلمة المرور\n3. اضغط "دخول"\n\nلو ناسي كلمة المرور:\n• اضغط "نسيت كلمة المرور"\n• أدخل البريد الإلكتروني\n• اتبع التعليمات المرسلة لبريدك\n\nلإنشاء حساب جديد:\n• اضغط "إنشاء حساب" في شاشة الدخول.';
    }

    if (_contains(lower, ['كلمة مرور', 'password', 'نسيت', 'reset'])) {
      return '🔑 استعادة كلمة المرور\n\nلاستعادة كلمة المرور:\n1. في شاشة الدخول اضغط "نسيت كلمة المرور؟"\n2. أدخل البريد الإلكتروني المسجل\n3. هيتبعتلك كود تحقق\n4. أدخل الكود\n5. اكتب كلمة المرور الجديدة\n\n⚠️ تأكد من التحقق من مجلد Spam لو مش لاقي الإيميل.';
    }

    // Language
    if (_contains(lower, ['لغة', 'language', 'عربي', 'arabic', 'english', 'انجليزي'])) {
      return '🌐 تغيير اللغة\n\nسلامتي بيدعم اللغتين العربية والإنجليزية.\n\nلتغيير اللغة:\n1. افتح الإعدادات\n2. اختار "اللغة / Language"\n3. اختار العربية أو الإنجليزية\n4. التطبيق هيتحدث تلقائياً\n\nالتطبيق بيدعم الـ RTL للعربية والـ LTR للإنجليزية.';
    }

    // Location
    if (_contains(lower, ['موقع', 'location', 'gps', 'مكان'])) {
      return '📍 خدمة الموقع\n\nسلامتي بيستخدم موقعك لـ:\n• إيجاد أقرب صيدلية\n• البحث عن مرافق قريبة منك\n• تحديد المسافات\n\nلو الموقع مش شغال:\n1. افتح إعدادات الجوال\n2. ابحث عن "سلامتي"\n3. فعّل إذن الموقع\n4. ارجع للتطبيق وجرب تاني';
    }

    // Notifications
    if (_contains(lower, ['إشعار', 'اشعار', 'notification', 'تنبيه'])) {
      return '🔔 الإشعارات\n\nقسم الإشعارات في سلامتي بيعرض:\n• تنبيهات الأدوية\n• أخبار طبية مهمة\n• تحديثات التأمين\n\nلإدارة الإشعارات:\n• اضغط على أيقونة الجرس في الشاشة الرئيسية\n• أو من الإعدادات اختار "الإشعارات"';
    }

    // Help / Support
    if (_contains(lower, ['مساعدة', 'دعم', 'help', 'support', 'مشكلة', 'بلاغ', 'تواصل'])) {
      return '🆘 الدعم الفني\n\nللتواصل مع فريق سلامتي:\n• من البروفايل اضغط "تواصل معنا"\n• هيظهر نموذج لإرسال استفسارك\n\nيمكنك أيضاً:\n• الإبلاغ عن مشكلة من داخل التطبيق\n• تقييم تجربتك لمساعدتنا في التحسين\n\nفريق الدعم جاهز لمساعدتك! 💪';
    }

    // Medical tips
    if (_contains(lower, ['نصيحة', 'نصائح', 'tips', 'tip', 'صحة', 'صحي'])) {
      return '💡 النصائح الطبية\n\nسلامتي بيقدم نصائح طبية مفيدة!\n\nلمشاهدة النصائح:\n• في الصفحة الرئيسية هتلاقي قسم "النصائح الطبية"\n• اضغط على أي نصيحة لقراءة التفاصيل\n• النصائح بتتحدث بانتظام\n\nالنصائح بتغطي مواضيع متنوعة زي:\n🍎 التغذية السليمة\n💊 الاستخدام الصحيح للأدوية\n🏃 النشاط البدني\n😴 الصحة النفسية';
    }

    // App features overview
    if (_contains(lower, ['ايه', 'إيه', 'what', 'خدمات', 'features', 'يعمل', 'وظيفة', 'اعرف'])) {
      return '📱 سلامتي - خدماتنا\n\nإحنا بنقدم:\n\n💊 الأدوية\n• بحث ومعلومات الأدوية\n• بدائل الأدوية\n• مسح الروشتات\n\n🏥 المرافق الطبية\n• صيدليات قريبة\n• مستشفيات وعيادات\n• تخصصات طبية\n\n🛡️ التأمين\n• إدارة وثيقة التأمين\n• خدمات التأمين القريبة\n\nإسألني عن أي خدمة!';
    }

    // Default fallback
    return '🤔 مش فاهم سؤالك كويس.\n\nتقدر تسألني عن:\n💊 الأدوية والبدائل\n📸 مسح الروشتة\n🏥 الصيدليات والمرافق\n🛡️ التأمين\n👨‍⚕️ التخصصات الطبية\n👤 الحساب والبروفايل\n\nاكتب موضوعك وأنا هساعدك! 😊';
  }

  static bool _contains(String text, List<String> keywords) {
    return keywords.any((k) => text.contains(k));
  }

  static List<String> getQuickReplies(String response) {
    if (response.contains('أدوية') || response.contains('دواء')) {
      return ['سعر دواء', 'بديل دواء', 'مسح روشتة'];
    }
    if (response.contains('صيدلية')) {
      return ['صيدليات قريبة', 'ساعات العمل', 'رجوع للرئيسية'];
    }
    if (response.contains('تأمين')) {
      return ['بيانات تأميني', 'شركات التأمين', 'خدمات مغطاة'];
    }
    return ['أدوية', 'صيدليات', 'تأمين', 'مساعدة'];
  }
}